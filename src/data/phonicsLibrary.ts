/**
 * Dynamic registry lookup & filtering
 */
export function getPhonicsSounds(language: AppLanguage, activeOnly = true): PhonicsSound[] {
  return PHONICS_SOUND_REGISTRY.filter(
    (s) => s.language === language && (activeOnly ? s.active : true)
  );
}

export function getPhonicsSoundById(soundId: string): PhonicsSound | undefined {
  return PHONICS_SOUND_REGISTRY.find((s) => s.soundId === soundId);
}

export function registerCustomPhonicsSound(sound: PhonicsSound): void {
  const idx = PHONICS_SOUND_REGISTRY.findIndex((s) => s.soundId === sound.soundId);
  if (idx >= 0) {
    PHONICS_SOUND_REGISTRY[idx] = sound;
  } else {
    PHONICS_SOUND_REGISTRY.push(sound);
  }
}
